DROP TABLE IF EXISTS ZEPTO;

CREATE TABLE ZEPTO (
    ID SERIAL PRIMARY KEY,
    CATEGORY VARCHAR(120),
    NAME VARCHAR(150) NOT NULL,
    MRP NUMERIC(8,2),
    DISCOUNTPERCENT NUMERIC(5,2),
    AVAILABLEQUANTITY INTEGER,
    DISCOUNTEDSELLINGPRICE NUMERIC(8,2),
    WEIGHTINGMS INTEGER,
    OUTOFSTOCK BOOLEAN,
    QUANTITY INTEGER
);


-- DATA EXPLORATION

SELECT COUNT(*) FROM ZEPTO;


-- SAMPLE DATA

SELECT * FROM ZEPTO LIMIT 10;


-- NULL VALUES

SELECT * FROM ZEPTO
WHERE NAME IS NULL
OR CATEGORY IS NULL
OR MRP IS NULL
OR DISCOUNTPERCENT IS NULL
OR DISCOUNTEDSELLINGPRICE IS NULL
OR WEIGHTINGMS IS NULL
OR AVAILABLEQUANTITY IS NULL
OR OUTOFSTOCK IS NULL
OR QUANTITY IS NULL;


-- DIFFERENT PRODUCT CATEGORIES

SELECT DISTINCT CATEGORY
FROM ZEPTO
ORDER BY CATEGORY;


-- INSTOCK AND OUTSTOCK PRODUCTS

SELECT OUTOFSTOCK, COUNT(ID)
FROM ZEPTO
GROUP BY OUTOFSTOCK;


-- PRODUCT NAMES PRESENT MULTIPLE TIMES

SELECT NAME, COUNT(ID) AS "NUMBER OF PRODUCT"
FROM ZEPTO
GROUP BY NAME
HAVING COUNT(ID) > 1
ORDER BY COUNT(ID) DESC;


-- DATA CLEANING

-- PRODUCT WITH PRICE MIGHT BE ZERO

SELECT *
FROM ZEPTO
WHERE MRP = 0
OR DISCOUNTEDSELLINGPRICE = 0;


-- WE HAVE ONE ROW WITH PRICE = 0

-- DELETING IT

DELETE FROM ZEPTO
WHERE MRP = 0;


-- SELLING PRICE AND DISCOUNTED PRICES ARE CURRENTLY IN PAISE

-- CONVERTING FROM PAISE TO RUPEES

UPDATE ZEPTO
SET MRP = MRP / 100.0,
    DISCOUNTEDSELLINGPRICE = DISCOUNTEDSELLINGPRICE / 100.0;


SELECT MRP, DISCOUNTEDSELLINGPRICE
FROM ZEPTO;


-- BUSINESS INSIGHTS


-- TOP 10 BEST VALUE-PRODUCTS BASED ON DISCOUNT PERCENTAGE

SELECT DISTINCT NAME, MRP, DISCOUNTPERCENT
FROM ZEPTO
ORDER BY DISCOUNTPERCENT DESC
LIMIT 10;

-- THESE PRODUCTS ARE BEING SOLD WITH ROUGHLY HALF OF THE PRICE
-- IT HELPS CUSTOMERS BECAUSE OF THE LOWER PURCHASE COST
-- IN BUSINESS VIEW IT CAN ATTRACT CUSTOMERS WHO WON'T BUY AT FULL PRICES
-- CUSTOMERS MIGHT SEE 50% DISCOUNT AND MAKE THEIR MIND TO TRY THE PLATFORM
-- IT IMPROVES PLATFORM ENGAGEMENT
-- THESE MIGHT REDUCE PROFIT MARGIN


-- HOW MUCH CUSTOMERS SAVE MONEY ON EACH PRODUCT

SELECT
    NAME,
    MRP,
    DISCOUNTEDSELLINGPRICE,
    MRP - DISCOUNTEDSELLINGPRICE AS DISCOUNT_AMOUNT,
    DISCOUNTPERCENT
FROM ZEPTO
ORDER BY DISCOUNT_AMOUNT DESC
LIMIT 10;


-- HIGHER DISCOUNT AMOUNTS CAN MAKE PRODUCTS MORE ATTRACTIVE TO CUSTOMERS
-- AND ENCOURAGE MORE PURCHASES.


-- PRODUCTS WITH HIGH MRP BUT OUT OF STOCK

SELECT DISTINCT NAME, MRP
FROM ZEPTO
WHERE OUTOFSTOCK = TRUE
AND MRP > 300
ORDER BY MRP DESC;

-- THESE ARE HIGH PRICED PRODUCTS
-- COMPANY MIGHT NEED TO RESTOCK THEM AS SOON AS POSSIBLE
-- IF CUSTOMERS ARE BUYING THEM FREQUENTLY


-- ESTIMATED REVENUE FOR EACH CATEGORY

SELECT CATEGORY,
SUM(DISCOUNTEDSELLINGPRICE * AVAILABLEQUANTITY) AS TOTAL_REVENUE
FROM ZEPTO
GROUP BY CATEGORY
ORDER BY TOTAL_REVENUE DESC;

-- THIS SHOWS WHICH CATEGORY CAN GENERATE THE MOST REVENUE
-- BASED ON THE CURRENT AVAILABLE INVENTORY


-- ALL PRODUCTS WHERE MRP IS GREATER THAN ₹500
-- AND DISCOUNT IS LESS THAN 10%

SELECT DISTINCT NAME, MRP, DISCOUNTPERCENT
FROM ZEPTO
WHERE MRP > 500
AND DISCOUNTPERCENT < 10
ORDER BY MRP DESC, DISCOUNTPERCENT DESC;

-- THESE ARE DAILY-USE PRODUCTS WITH HIGH MRP BUT VERY LOW DISCOUNTS
-- THIS MAY INDICATE THAT CUSTOMERS REGULARLY NEED THEM
-- AND THERE MAY BE LESS NEED FOR HEAVY DISCOUNTS


-- TOP 5 CATEGORIES OFFERING THE HIGHEST AVERAGE DISCOUNT PERCENTAGE

SELECT CATEGORY,
ROUND(AVG(DISCOUNTPERCENT), 2) AS AVG_DISCOUNT
FROM ZEPTO
GROUP BY CATEGORY
ORDER BY AVG_DISCOUNT DESC
LIMIT 5;

-- THIS IS VERY USEFUL FOR MARKETING TEAMS
-- TO SEE WHERE THE PRICE CUT IS HAPPENING MOST


-- THE PRICE PER GRAM FOR PRODUCTS ABOVE 100G
-- AND SORT BY BEST VALUE

SELECT DISTINCT NAME, WEIGHTINGMS, DISCOUNTEDSELLINGPRICE,
ROUND(DISCOUNTEDSELLINGPRICE / WEIGHTINGMS, 2) AS PRICE_PER_GRAM
FROM ZEPTO
WHERE WEIGHTINGMS >= 100
ORDER BY PRICE_PER_GRAM ASC;

-- THIS HELPS CUSTOMERS TO COMPARE VALUE FOR MONEY FOR PRODUCTS
-- AND EVEN FOR INTERNAL PRICING STRATEGIES
-- FOR EXAMPLE, IF WE HAVE PROTEIN PRODUCTS,
-- WE COULD USE A SIMILAR APPROACH TO SHOW HOW MUCH CUSTOMERS
-- PAY FOR EACH GRAM OF PROTEIN.


-- GROUP THE PRODUCTS INTO CATEGORIES LIKE LOW, MEDIUM, BULK

SELECT DISTINCT NAME, WEIGHTINGMS,
CASE
    WHEN WEIGHTINGMS < 1000 THEN 'LOW'
    WHEN WEIGHTINGMS < 5000 THEN 'MEDIUM'
    ELSE 'BULK'
END AS WEIGHT_CATEGORY
FROM ZEPTO;


-- THIS HELPS US UNDERSTAND WHETHER PRODUCTS ARE MAINLY
-- SOLD IN SMALL, MEDIUM OR BULK PACK SIZES


-- THE TOTAL INVENTORY WEIGHT PER CATEGORY

SELECT CATEGORY,
SUM(WEIGHTINGMS * AVAILABLEQUANTITY) AS TOTAL_WEIGHT
FROM ZEPTO
GROUP BY CATEGORY
ORDER BY TOTAL_WEIGHT DESC;

-- THIS HELPS IN INVENTORY MANAGEMENT AND WAREHOUSE PLANNING


