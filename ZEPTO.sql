-- PRODUCTS WITH DISCOUNT HIGHER THAN THE AVERAGE DISCOUNT

SELECT
    NAME,
    CATEGORY,
    DISCOUNTPERCENT
FROM ZEPTO
WHERE DISCOUNTPERCENT > (
    SELECT AVG(DISCOUNTPERCENT)
    FROM ZEPTO
)
ORDER BY DISCOUNTPERCENT DESC;

-- THIS HELPS US FIND PRODUCTS WHERE THE DISCOUNT
-- IS HIGHER THAN THE OVERALL AVERAGE DISCOUNT
-- THESE PRODUCTS ARE GETTING MORE DISCOUNT THAN MOST PRODUCTS


-- CATEGORY WISE AVERAGE DISCOUNT

WITH CATEGORY_DISCOUNT AS (
    SELECT
        CATEGORY,
        ROUND(AVG(DISCOUNTPERCENT), 2) AS AVG_DISCOUNT
    FROM ZEPTO
    GROUP BY CATEGORY
)
SELECT
    CATEGORY,
    AVG_DISCOUNT
FROM CATEGORY_DISCOUNT
ORDER BY AVG_DISCOUNT DESC;

-- THIS HELPS US UNDERSTAND WHICH CATEGORIES
-- ARE GETTING MORE DISCOUNTS ON AVERAGE
-- THIS IS USEFUL FOR MARKETING TEAMS
-- TO SEE WHERE THE PRICE CUT IS HAPPENING MOST


-- TOP 3 PRODUCTS WITH HIGHEST DISCOUNT
-- FROM EACH CATEGORY

WITH RANKED_PRODUCTS AS (
    SELECT
        CATEGORY,
        NAME,
        DISCOUNTPERCENT,
        ROW_NUMBER() OVER (
            PARTITION BY CATEGORY
            ORDER BY DISCOUNTPERCENT DESC
        ) AS PRODUCT_RANK
    FROM ZEPTO
)
SELECT
    CATEGORY,
    NAME,
    DISCOUNTPERCENT,
    PRODUCT_RANK
FROM RANKED_PRODUCTS
WHERE PRODUCT_RANK <= 3
ORDER BY CATEGORY, PRODUCT_RANK;

-- THIS HELPS US FIND THE PRODUCTS WITH THE HIGHEST DISCOUNTS
-- INSIDE EACH CATEGORY
-- THIS CAN HELP US UNDERSTAND WHICH PRODUCTS
-- ARE BEING PROMOTED MORE IN EACH CATEGORY


-- RANK PRODUCTS BASED ON DISCOUNT
-- WITHIN EACH CATEGORY

SELECT
    CATEGORY,
    NAME,
    DISCOUNTPERCENT,
    RANK() OVER (
        PARTITION BY CATEGORY
        ORDER BY DISCOUNTPERCENT DESC
    ) AS DISCOUNT_RANK
FROM ZEPTO
ORDER BY CATEGORY, DISCOUNT_RANK;

-- THIS HELPS US COMPARE PRODUCTS WITHIN THE SAME CATEGORY
-- AND FIND WHICH PRODUCTS HAVE THE HIGHEST DISCOUNT
-- COMPARED TO OTHER PRODUCTS IN THE SAME CATEGORY


-- TOP 3 PRODUCTS BASED ON DISCOUNT AMOUNT
-- WITHIN EACH CATEGORY

WITH DISCOUNT_AMOUNT_DATA AS (
    SELECT
        CATEGORY,
        NAME,
        MRP,
        DISCOUNTEDSELLINGPRICE,
        MRP - DISCOUNTEDSELLINGPRICE AS DISCOUNT_AMOUNT
    FROM ZEPTO
),
RANKED_DISCOUNTS AS (
    SELECT
        CATEGORY,
        NAME,
        MRP,
        DISCOUNTEDSELLINGPRICE,
        DISCOUNT_AMOUNT,
        ROW_NUMBER() OVER (
            PARTITION BY CATEGORY
            ORDER BY DISCOUNT_AMOUNT DESC
        ) AS DISCOUNT_RANK
    FROM DISCOUNT_AMOUNT_DATA
)
SELECT
    CATEGORY,
    NAME,
    MRP,
    DISCOUNTEDSELLINGPRICE,
    DISCOUNT_AMOUNT,
    DISCOUNT_RANK
FROM RANKED_DISCOUNTS
WHERE DISCOUNT_RANK <= 3
ORDER BY CATEGORY, DISCOUNT_RANK;

-- THIS HELPS US FIND WHICH PRODUCTS GIVE CUSTOMERS
-- THE HIGHEST DISCOUNT AMOUNT WITHIN EACH CATEGORY
-- THIS CAN HELP CUSTOMERS FIND PRODUCTS WHERE THEY SAVE MORE MONEY


-- TOP 10 PRODUCTS WITH HIGHEST CURRENT INVENTORY VALUE

SELECT
    NAME,
    CATEGORY,
    AVAILABLEQUANTITY,
    DISCOUNTEDSELLINGPRICE,
    DISCOUNTEDSELLINGPRICE * AVAILABLEQUANTITY AS INVENTORY_VALUE
FROM ZEPTO
ORDER BY INVENTORY_VALUE DESC
LIMIT 10;

-- THIS SHOWS WHICH PRODUCTS HAVE THE HIGHEST CURRENT
-- INVENTORY VALUE BASED ON AVAILABLE STOCK AND SELLING PRICE
-- THIS CAN HELP THE BUSINESS UNDERSTAND WHICH PRODUCTS
-- HAVE MORE MONEY CURRENTLY TIED UP IN INVENTORY


-- PRODUCTS WITH HIGH DISCOUNT AND LOW AVAILABLE STOCK

SELECT
    NAME,
    CATEGORY,
    DISCOUNTPERCENT,
    AVAILABLEQUANTITY,
    OUTOFSTOCK
FROM ZEPTO
WHERE DISCOUNTPERCENT >= 30
AND AVAILABLEQUANTITY <= 3
ORDER BY DISCOUNTPERCENT DESC;

-- THESE PRODUCTS HAVE HIGH DISCOUNTS BUT LOW AVAILABLE STOCK
-- THIS CAN HELP THE BUSINESS IDENTIFY PRODUCTS
-- THAT MAY NEED BETTER INVENTORY PLANNING
-- ESPECIALLY WHEN PRODUCTS ARE BEING PROMOTED